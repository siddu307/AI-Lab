import random

class NQueensHillClimbing:
    def __init__(self, n):
        self.n = n

    def get_attacks(self, state):
        attacks = 0
        for i in range(self.n):
            for j in range(i + 1, self.n):
                if state[i] == state[j] or abs(state[i] - state[j]) == abs(i - j):
                    attacks += 1
        return attacks

    def get_best_neighbor(self, state):
        best_state = list(state)
        min_attacks = self.get_attacks(state)

        for col in range(self.n):
            original_row = state[col]
            for row in range(self.n):
                if row == original_row:
                    continue
                neighbor = list(state)
                neighbor[col] = row
                attacks = self.get_attacks(neighbor)
                if attacks < min_attacks:
                    min_attacks = attacks
                    best_state = neighbor

        return best_state, min_attacks

    def solve(self, max_restarts=1000):
        for restart in range(max_restarts):
            current_state = [random.randint(0, self.n - 1) for _ in range(self.n)]
            current_attacks = self.get_attacks(current_state)

            if current_attacks == 0:
                return current_state

            while True:
                next_state, next_attacks = self.get_best_neighbor(current_state)

                if next_attacks >= current_attacks:
                    break

                current_state = next_state
                current_attacks = next_attacks

                if current_attacks == 0:
                    return current_state

        return None

    def print_board(self, state):
        if not state:
            print("No solution found.")
            return
        for r in range(self.n):
            row_str = ""
            for c in range(self.n):
                if state[c] == r:
                    row_str += " Q "
                else:
                    row_str += " . "
            print(row_str)
        print()
if __name__ == "__main__":
    n = 8
    solver = NQueensHillClimbing(n)
    solution = solver.solve()

    print(f"Solution vector (Column -> Row): {solution}")
    print("Board Layout:")
    solver.print_board(solution)