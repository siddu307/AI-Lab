import heapq
GOAL=(1,2,3,8,0,4,7,6,5)

def misplaced_tiles(state):
    count=0
    for i in range(9):
        if state[i]!=0 and state[i]!=GOAL[i]:
            count+=1
    return count

def manhattan_distance(state):
    distance=0
    for i in range(9):
        tile=state[i]
        if tile!=0:
            r1,c1 = i//3 , i%3
            j=GOAL.index(tile)
            r2,c2 = j//3, j%3
            distance+=abs(r1-r2) + abs(c1-c2)
    return distance

def get_neighbors(state):
    neighbors=[]
    zero=state.index(0)
    row,col = zero//3, zero%3

    for dr,dc in [(-1,0),(1,0),(0,-1),(0,1)]:
        r,c = row+dr, col+dc

        if 0<=r<3 and 0<=c<3:
            j = r*3+c
            new_state = list(state)
            new_state[zero],new_state[j]=new_state[j],new_state[zero]
            neighbors.append(tuple(new_state))

    return neighbors

def a_star(initial, heuristic):
    open_list = [(heuristic(initial), 0, initial)]
    g_cost = {initial: 0}
    parent = {initial: None}
    closed = set()

    while open_list:
        f,g,current = heapq.heappop(open_list)

        if current==GOAL:
            path=[]
            while current is not None:
                path.append(current)
                current=parent[current]
            return path[::-1]

        if current in closed:
            continue

        closed.add(current)

        for neighbor in get_neighbors(current):
            new_g=g + 1

            if neighbor not in g_cost or new_g < g_cost[neighbor]:
                g_cost[neighbor]=new_g
                parent[neighbor]=current
                new_f=new_g+heuristic(neighbor)
                heapq.heappush(open_list,(new_f,new_g,neighbor))

    return None

def print_puzzle(state):
    for i in range(0, 9, 3):
        print(state[i:i + 3])
    print()

initial=(2,8,3,1,6,4,0,7,5)

print("Misplaced Tiles Heuristic")
path=a_star(initial,misplaced_tiles)

if path:
    print("Number of moves:",len(path)-1)
    for state in path:
        print_puzzle(state)
else:
    print("No solution")

print("Manhattan Distance Heuristic")
path = a_star(initial,manhattan_distance)

if path:
    print("Number of moves:",len(path) - 1)
    for state in path:
        print_puzzle(state)
else:
    print("No solution")