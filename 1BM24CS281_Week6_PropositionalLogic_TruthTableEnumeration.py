from itertools import product

def implies(a, b):
    return not a or b

def KB(model):
    P, Q, R = model["P"], model["Q"], model["R"]
    return (implies(Q, P) and
            implies(P, not Q) and
            (Q or R))

def TT_CHECK_ALL(query, symbols, model):
    if not symbols:
        if KB(model):
            return query(model)
        return True

    symbol = symbols[0]
    rest = symbols[1:]

    model_true = {**model, symbol: True}
    model_false = {**model, symbol: False}

    return (TT_CHECK_ALL(query, rest, model_true) and
            TT_CHECK_ALL(query, rest, model_false))

def TT_ENTAILS(query):
    return TT_CHECK_ALL(query, ["P", "Q", "R"], {})

queries = {
    "R": lambda m: m["R"],
    "R -> P": lambda m: implies(m["R"], m["P"]),
    "Q -> R": lambda m: implies(m["Q"], m["R"])
}

print("P Q R | KB")
for P, Q, R in product([False, True], repeat=3):
    model = {"P": P, "Q": Q, "R": R}
    print(int(P), int(Q), int(R), "|", int(KB(model)))

print("\nEntailment Results:")
for name, query in queries.items():
    print(f"KB entails {name}: {TT_ENTAILS(query)}")